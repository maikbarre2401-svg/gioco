const dictionaries = { it, en };

export type Lang = keyof typeof dictionaries;

export function resolveLanguage(pref: Language): Lang {
  if (pref !== 'system') return pref;
  const code = getLocales()[0]?.languageCode ?? 'it';
  return code === 'it' ? 'it' : code === 'en' ? 'en' : 'it';
}

export function localeFor(lang: Lang): string {
  return lang === 'it' ? 'it-IT' : 'en-GB';
}

export type Translate = (key: TKey, params?: Record<string, string | number>) => string;

export function makeTranslator(lang: Lang): Translate {
  const dict = dictionaries[lang];
  return (key, params) => {
    let s = dict[key] ?? it[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
    }
    return s;
  };
}

export function categoryLabel(t: Translate, id: CategoryId): string {
  return t(`cat_${id}` as TKey);
}

export function cycleLabel(t: Translate, unit: CycleUnit, every: number): string {
  const key = `cycle_${unit}_${every}` as TKey;
  if (key in it) return t(key);
  return t('everyN', { n: every, unit: t(`unit_${unit}` as TKey) });
}

export function reminderLabel(t: Translate, days: number): string {
  if (days === 0) return t('reminderSameDay');
  return t(days === 1 ? 'reminderDay' : 'reminderDays', { n: days });
}
